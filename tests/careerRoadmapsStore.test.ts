import { describe, it, expect, beforeEach, vi } from 'vitest';
import { CareerRoadmapsStore } from '../server/services/career/careerRoadmapsStore.js';
import { CURATED_ROADMAPS } from '../server/services/career/careerRoadmapsSeed.js';
import { CURATED_CAREER_ROLES } from '../server/services/career/careerRolesSeed.js';
import * as supabaseModule from '../server/db/supabase.js';

describe('Stage 7.2 — CareerRoadmapsStore', () => {
  beforeEach(() => {
    CareerRoadmapsStore.resetFallbackRoadmaps();
  });

  describe('Curated Library & Content Integrity', () => {
    it('contains exactly 6 published launch roadmaps for approved Stage 7.2 roles', () => {
      expect(CURATED_ROADMAPS.length).toBe(6);
      expect(CURATED_ROADMAPS.every(rm => rm.status === 'published')).toBe(true);
      expect(CURATED_ROADMAPS.every(rm => rm.version === 1 && rm.version_label === 'v1')).toBe(true);
    });

    it('every published roadmap references a valid published launch career role', () => {
      const roleIdSet = new Set(CURATED_CAREER_ROLES.map(r => r.id));
      for (const rm of CURATED_ROADMAPS) {
        expect(roleIdSet.has(rm.career_role_id)).toBe(true);
      }
    });

    it('roadmap stages strictly adhere to governed 3-stage taxonomy (foundation, core, advanced)', () => {
      const validStages = new Set(['foundation', 'core', 'advanced']);
      for (const rm of CURATED_ROADMAPS) {
        for (const item of rm.items) {
          expect(validStages.has(item.stage)).toBe(true);
        }
      }
    });

    it('each roadmap contains meaningful depth across Foundation, Core, and Advanced stages', () => {
      for (const rm of CURATED_ROADMAPS) {
        const foundationCount = rm.items.filter(i => i.stage === 'foundation').length;
        const coreCount = rm.items.filter(i => i.stage === 'core').length;
        const advancedCount = rm.items.filter(i => i.stage === 'advanced').length;

        expect(foundationCount).toBeGreaterThanOrEqual(3);
        expect(coreCount).toBeGreaterThanOrEqual(4);
        expect(advancedCount).toBeGreaterThanOrEqual(2);
      }
    });

    it('every roadmap item contains non-empty descriptions, why_it_matters, and competency_outcome', () => {
      for (const rm of CURATED_ROADMAPS) {
        for (const item of rm.items) {
          expect(item.skill_name.trim().length).toBeGreaterThanOrEqual(2);
          expect(item.skill_category.trim().length).toBeGreaterThanOrEqual(2);
          expect(item.description.trim().length).toBeGreaterThanOrEqual(10);
          expect(item.why_it_matters.trim().length).toBeGreaterThanOrEqual(10);
          expect(item.competency_outcome.trim().length).toBeGreaterThanOrEqual(10);
          expect(Array.isArray(item.evidence_examples)).toBe(true);
          expect(item.evidence_examples.length).toBeGreaterThanOrEqual(2);
          expect(item.evidence_examples.every(e => typeof e === 'string' && e.trim().length > 0)).toBe(true);
        }
      }
    });

    it('display order is non-negative and unique within each stage', () => {
      for (const rm of CURATED_ROADMAPS) {
        for (const stage of ['foundation', 'core', 'advanced'] as const) {
          const stageItems = rm.items.filter(i => i.stage === stage);
          const orders = stageItems.map(i => i.display_order);
          expect(orders.every(o => o >= 0)).toBe(true);
          const uniqueOrders = new Set(orders);
          expect(uniqueOrders.size).toBe(orders.length);
        }
      }
    });

    it('operates with zero AI claims, no speculative salary figures, and no course provider marketplace URLs', () => {
      for (const rm of CURATED_ROADMAPS) {
        const rmSerialized = JSON.stringify(rm);
        // Zero salary claims
        expect(rmSerialized).not.toMatch(/£\d+|\$\d+|salary|compensation range|per annum/i);
        // Zero course provider marketplace links
        expect(rmSerialized).not.toMatch(/https?:\/\/|coursera|udemy|edx|pluralsight/i);
        // Zero AI claims
        expect(rmSerialized).not.toMatch(/generated by ai|ai recommendation/i);
      }
    });
  });

  describe('Retrieval by Role Slug', () => {
    it('retrieves published roadmap for frontend-engineer', async () => {
      const result = await CareerRoadmapsStore.getRoadmapByRoleSlug('frontend-engineer');
      expect(result).not.toBeNull();
      expect(result?.role.slug).toBe('frontend-engineer');
      expect(result?.roadmap).not.toBeNull();
      expect(result?.roadmap?.title).toContain('Frontend Engineering');
      expect(result?.roadmap?.items.length).toBeGreaterThan(0);
    });

    it('returns role with roadmap: null for published role without roadmap (e.g. mobile-developer)', async () => {
      const result = await CareerRoadmapsStore.getRoadmapByRoleSlug('mobile-developer');
      expect(result).not.toBeNull();
      expect(result?.role.slug).toBe('mobile-developer');
      expect(result?.roadmap).toBeNull();
      expect(result?.message).toContain('No published roadmap');
    });

    it('returns null for nonexistent role slug', async () => {
      const result = await CareerRoadmapsStore.getRoadmapByRoleSlug('nonexistent-role-slug');
      expect(result).toBeNull();
    });

    it('read queries cause zero state mutations across records', async () => {
      const before = await CareerRoadmapsStore.getRoadmapByRoleSlug('frontend-engineer');
      const after = await CareerRoadmapsStore.getRoadmapByRoleSlug('frontend-engineer');
      expect(before?.roadmap?.items.length).toBe(after?.roadmap?.items.length);
    });
  });

  describe('Production Environment Gating', () => {
    it('strictly fails closed in production environment if client is unavailable', async () => {
      const originalEnv = process.env.NODE_ENV;
      const spy = vi.spyOn(supabaseModule, 'getAdminClient').mockReturnValue(null as any);
      try {
        process.env.NODE_ENV = 'production';
        await expect(CareerRoadmapsStore.getRoadmapByRoleSlug('frontend-engineer')).rejects.toThrow('DATABASE_ERROR');
      } finally {
        spy.mockRestore();
        process.env.NODE_ENV = originalEnv;
      }
    });

    it('strictly fails closed in production when database query returns error', async () => {
      const originalEnv = process.env.NODE_ENV;
      const createChainableError = () => {
        const promise = Promise.resolve({ data: null, error: { message: 'connection failure' } });
        const chain: any = {
          then: promise.then.bind(promise),
          catch: promise.catch.bind(promise),
          select: () => chain,
          eq: () => chain,
          order: () => chain,
          maybeSingle: () => Promise.resolve({ data: null, error: { message: 'connection failure' } }),
        };
        return chain;
      };
      const mockSupabase = {
        from: () => createChainableError(),
      };
      const spy = vi.spyOn(supabaseModule, 'getAdminClient').mockReturnValue(mockSupabase as any);
      try {
        process.env.NODE_ENV = 'production';
        await expect(CareerRoadmapsStore.getRoadmapByRoleSlug('frontend-engineer')).rejects.toThrow('DATABASE_ERROR');
      } finally {
        spy.mockRestore();
        process.env.NODE_ENV = originalEnv;
      }
    });

    it('returns roadmap: null in production if role has no published roadmap record in database', async () => {
      const originalEnv = process.env.NODE_ENV;
      const mockSupabase = {
        from: (table: string) => {
          if (table === 'career_roles') {
            return {
              select: () => ({
                eq: () => ({
                  eq: () => ({
                    maybeSingle: () => Promise.resolve({
                      data: {
                        id: 'a1000000-0000-0000-0000-000000000001',
                        slug: 'frontend-engineer',
                        title: 'Frontend Engineer',
                        career_area: 'Software Engineering',
                        status: 'published'
                      },
                      error: null
                    }),
                  }),
                }),
              }),
            };
          }
          // career_role_roadmaps returns null
          return {
            select: () => ({
              eq: () => ({
                eq: () => ({
                  order: () => ({
                    limit: () => ({
                      maybeSingle: () => Promise.resolve({ data: null, error: null }),
                    }),
                    maybeSingle: () => Promise.resolve({ data: null, error: null }),
                  }),
                }),
              }),
            }),
          };
        },
      };
      const spy = vi.spyOn(supabaseModule, 'getAdminClient').mockReturnValue(mockSupabase as any);
      try {
        process.env.NODE_ENV = 'production';
        const result = await CareerRoadmapsStore.getRoadmapByRoleSlug('frontend-engineer');
        expect(result).not.toBeNull();
        expect(result?.roadmap).toBeNull();
      } finally {
        spy.mockRestore();
        process.env.NODE_ENV = originalEnv;
      }
    });

    it('production query path orders by version DESC, limits 1, and selects highest version', async () => {
      const originalEnv = process.env.NODE_ENV;
      const queryRecorded: any = {};
      const mockSupabase = {
        from: (table: string) => {
          if (table === 'career_roles') {
            return {
              select: () => ({
                eq: () => ({
                  eq: () => ({
                    maybeSingle: () => Promise.resolve({
                      data: {
                        id: 'a1000000-0000-0000-0000-000000000001',
                        slug: 'frontend-engineer',
                        title: 'Frontend Engineer',
                        career_area: 'Software Engineering',
                        status: 'published'
                      },
                      error: null
                    }),
                  }),
                }),
              }),
            };
          }
          if (table === 'career_role_roadmaps') {
            return {
              select: () => ({
                eq: (col1: string, val1: any) => ({
                  eq: (col2: string, val2: any) => ({
                    order: (orderCol: string, orderOpts: any) => ({
                      limit: (limitNum: number) => {
                        queryRecorded.table = table;
                        queryRecorded.filters = { [col1]: val1, [col2]: val2 };
                        queryRecorded.order = { orderCol, orderOpts };
                        queryRecorded.limit = limitNum;
                        return {
                          maybeSingle: () => Promise.resolve({
                            data: {
                              id: 'rm-v2-id',
                              career_role_id: 'a1000000-0000-0000-0000-000000000001',
                              version: 2,
                              version_label: 'v2',
                              title: 'Frontend Engineer Roadmap v2',
                              summary: 'Advanced modern roadmap v2',
                              status: 'published',
                              created_at: '2026-03-01T00:00:00Z',
                              updated_at: '2026-03-01T00:00:00Z'
                            },
                            error: null
                          })
                        };
                      }
                    })
                  })
                })
              })
            };
          }
          // career_role_roadmap_items
          return {
            select: () => ({
              eq: () => ({
                order: () => Promise.resolve({
                  data: [
                    {
                      id: 'item-1-id',
                      roadmap_id: 'rm-v2-id',
                      stage: 'foundation',
                      skill_name: 'HTML5 & CSS3',
                      skill_category: 'core_technical',
                      description: 'Semantic markup and responsive layouts',
                      why_it_matters: 'Forms the bedrock of accessible web interfaces',
                      competency_outcome: 'Build accessible, responsive UI pages',
                      evidence_examples: ['Responsive site', 'WCAG audit'],
                      display_order: 1,
                      created_at: '2026-03-01T00:00:00Z',
                      updated_at: '2026-03-01T00:00:00Z'
                    }
                  ],
                  error: null
                })
              })
            })
          };
        }
      };
      const spy = vi.spyOn(supabaseModule, 'getAdminClient').mockReturnValue(mockSupabase as any);
      try {
        process.env.NODE_ENV = 'production';
        const result = await CareerRoadmapsStore.getRoadmapByRoleSlug('frontend-engineer');
        expect(result).not.toBeNull();
        expect(result?.roadmap?.version).toBe(2);
        expect(result?.roadmap?.title).toBe('Frontend Engineer Roadmap v2');
        expect(queryRecorded.table).toBe('career_role_roadmaps');
        expect(queryRecorded.filters.status).toBe('published');
        expect(queryRecorded.order).toEqual({ orderCol: 'version', orderOpts: { ascending: false } });
        expect(queryRecorded.limit).toBe(1);
      } finally {
        spy.mockRestore();
        process.env.NODE_ENV = originalEnv;
      }
    });
  });
});
